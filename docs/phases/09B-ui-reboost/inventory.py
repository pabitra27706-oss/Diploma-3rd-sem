#!/usr/bin/env python3
"""Generate source inventory; analysis-only: python -m pip install tinycss2==1.5.1."""
from collections import Counter, defaultdict
from pathlib import Path
import re
import tinycss2 as css

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).with_name('inventory.md')
files = sorted(p for p in ROOT.rglob('*.css') if not ({'.git', 'webflow', 'node_modules', 'tests', '.github'} & set(p.relative_to(ROOT).parts)) and not str(p.relative_to(ROOT)).startswith('assets/vendor/'))
props = ['font-size','line-height','font-weight','letter-spacing','font-family','padding','margin','gap','border-radius','box-shadow','z-index']
values = {p:defaultdict(Counter) for p in props}
rgba = defaultdict(Counter)
component = {k:defaultdict(set) for k in ['button','card','pill/badge','panel/notice','table','form']}
states = defaultdict(Counter)

def family(p):
    for x in ('padding','margin','gap','border-radius'):
        if p == x or p.startswith(x+'-') or (x=='gap' and p in ('row-gap','column-gap')): return x
    return p if p in props else None

def functions(tokens, rel):
    for t in tokens:
        if t.type=='function':
            if t.lower_name=='rgba': rgba[css.serialize([t]).strip()][rel]+=1
            functions(t.arguments,rel)
        elif hasattr(t,'content') and t.content is not None: functions(t.content,rel)

def scan(nodes, rel):
    for node in nodes:
        if node.type == 'qualified-rule':
            selector=css.serialize(node.prelude).strip()
            classes=set(re.findall(r'\.([a-zA-Z_][\w-]*)',selector))
            for c in classes:
                cl=c.lower()
                categories=[]
                if re.search(r'(^|[-_])(btn|button)([-_]|$)',cl): categories.append('button')
                if re.search(r'(^|[-_])card([-_]|$)',cl): categories.append('card')
                if re.search(r'(^|[-_])(pill|badge|chip)([-_]|$)',cl): categories.append('pill/badge')
                if re.search(r'(^|[-_])(panel|notice|alert)([-_]|$)',cl): categories.append('panel/notice')
                if re.search(r'(^|[-_])table([-_]|$)',cl): categories.append('table')
                if re.search(r'(^|[-_])(input|select|textarea|form)([-_]|$)',cl): categories.append('form')
                for cat in categories: component[cat][rel].add(c)
            for st in ('hover','focus','focus-visible','active','disabled','empty','loading','error'):
                if re.search(r'(?<![\w-])'+re.escape(st)+r'(?![\w-])',selector,re.I): states[st][rel]+=1
            for d in css.parse_declaration_list(node.content,skip_comments=True,skip_whitespace=True):
                if d.type != 'declaration': continue
                key=family(d.lower_name)
                if key:
                    val=css.serialize(d.value).strip()+(' !important' if d.important else '')
                    values[key][(d.lower_name,val)][rel]+=1
                functions(d.value,rel)
        elif node.type=='at-rule' and node.content is not None and node.lower_at_keyword not in ('font-face','page','property'):
            scan(css.parse_rule_list(node.content,skip_comments=True,skip_whitespace=True),rel)

for f in files: scan(css.parse_stylesheet(f.read_text(),skip_comments=True,skip_whitespace=True),str(f.relative_to(ROOT)))
palette = dict(re.findall(r'^\s*(--c-[a-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;', (ROOT/'assets/css/variables.css').read_text(),re.M))
refs=defaultdict(Counter)
for f in files:
    rel=str(f.relative_to(ROOT)); text=re.sub(r'/\*.*?\*/','',f.read_text(),flags=re.S)
    for name in re.findall(r'var\(\s*(--c-[\w-]+)',text): refs[name][rel]+=1

def loc(counter): return ', '.join(f'{k} ({v})' for k,v in sorted(counter.items())) or '—'
def safe(s): return s.replace('|','\\|').replace('`','\\`').replace('\n',' ')
lines=['# Source inventory — Phase 9B','',f'Generated by `inventory.py` with tinycss2 1.5.1; {len(files)} first-party CSS files (vendor excluded). A count is a parsed CSS declaration occurrence, not a computed style. Distinct values preserve spelling and shorthand; individual longhands remain separate. Custom-property definitions, font shorthands, inline HTML/JS styles, browser defaults and dynamic DOM are not expanded. Counts are not visual usage.','', '## Files','']+[f'- `{f.relative_to(ROOT)}`' for f in files]
for p in props:
    bucket=values[p]; lines += ['',f'## {p}', '', f'{len(bucket)} distinct property/value pairs, {len(set(v for _,v in bucket))} distinct raw values, {sum(sum(c.values()) for c in bucket.values())} declarations.','', '| Property | Value | Count | Files (declarations) |','|---|---|---:|---|']
    for (prop,val), ctr in sorted(bucket.items(), key=lambda item:(item[0][1].lower(),item[0][0])):
        lines.append(f'| `{prop}` | `{safe(val)}` | {sum(ctr.values())} | {loc(ctr)} |')
lines+=['','## Palette references in first-party stylesheets','', 'Counts of `var(--c-...)` references in CSS, including fallbacks and aliases, excluding comments; not runtime frequency, and not inline HTML/JS references. Zero means no CSS reference, not necessarily no reference anywhere.','', '| Token | Value | CSS references | Files |','|---|---|---:|---|']
for name,value in sorted(palette.items(),key=lambda x:(-sum(refs[x[0]].values()),x[0])):
    lines.append(f'| `{name}` | `{value}` | {sum(refs[name].values())} | {loc(refs[name])} |')
lines+=['','## rgba functions','',f'{sum(sum(c.values()) for c in rgba.values())} occurrences, {len(rgba)} distinct serialized expressions in declarations. Textually different whitespace is distinct; occurrences inside CSS custom-property definitions count.','', '| Expression | Count | Files |','|---|---:|---|']
for v,c in sorted(rgba.items(),key=lambda x:(-sum(x[1].values()),x[0])): lines.append(f'| `{safe(v)}` | {sum(c.values())} | {loc(c)} |')
lines+=['','## Component class candidates','', 'A reproducible lexical inventory, not a count of rendered instances or proven visual variants. It includes modifiers and internal elements; semantic components with other names or inline/JS styling may be missed. For each family, class names are deduplicated per file; the same class in two files is counted twice.','']
for k,perfile in component.items():
    lines += [f'### {k} — {sum(map(len,perfile.values()))} file/class pairs','']
    for f,names in sorted(perfile.items()): lines.append(f'- `{f}` ({len(names)}): '+', '.join(f'`{n}`' for n in sorted(names)))
    lines.append('')
lines += ['## State selector evidence','', 'Count of CSS rule selectors mentioning each word; this is not proof that every interactive element has the state.','', '| State | Rules | Files (rules) |','|---|---:|---|']
for k,v in states.items(): lines.append(f'| {k} | {sum(v.values())} | {loc(v)} |')
OUT.write_text('\n'.join(lines)+'\n')
print('files',len(files),'rgba',sum(sum(c.values()) for c in rgba.values()),'distinct',len(rgba),'palette css refs',sum(sum(v.values()) for v in refs.values()))
for p in props: print(p,len(set(v for _,v in values[p])),sum(sum(c.values()) for c in values[p].values()))
for k,v in component.items(): print(k,sum(map(len,v.values())))
print('largest', sorted(((sum(v.values()), k) for k,v in refs.items()),reverse=True)[:10], 'zero',sum(not refs[k] for k in palette))
