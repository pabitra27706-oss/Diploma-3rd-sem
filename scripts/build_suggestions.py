def build(root=ROOT):
    authored = load(root / CURATION)
    syllabus = load(root / SYLLABUS)
    subjects = {s['code']: s for s in syllabus['subjects']}
    if set(subjects) != set(authored) or set(authored) != set(SUBJECTS):
        raise ValueError('Suggestions must cover exactly the theory courses in the syllabus')
    version = shell_version(root)
    hub = Path(HUB)
    output = {hub: page(hub, version, 'Study Suggestions',
                        'Past exam questions and quick revision guides for the CST 3rd-semester theory subjects.',
                        hub_body(authored))}
    for code, (slug, name, _) in SUBJECTS.items():
        subject, guide = subjects[code], authored[code]
        units = {u['unit']: u['title'] for u in subject['units']}
        order = guide['studyOrder']
        if set(guide['units']) != {str(u) for u in units} or sorted(order) != sorted(units):
            raise ValueError(f'{code}: the selected units and study order must cover the syllabus once each')
        archive = archived_questions(root, code)
        patterns = {unit: unit_patterns(guide['units'][str(unit)]['patterns'], archive, f'{code} Unit {unit}')
                    for unit in units}
        pages = {
            'important-questions': (
                workbook_body(code, units, guide['units'], patterns),
                f'Practise {name} question patterns by syllabus unit, with star ratings and links to dated past papers.',
            ),
            'easy-read': (
                priority_body(root, code, units, guide, patterns, archive),
                f'What to study first in {name}: priority topics, sections to read, short drills and dated past-paper practice.',
            ),
        }
        for kind, (body, desc) in pages.items():
            path = Path(f'suggestions/{slug}/{kind}.html')
            header = guide_header(kind, code, name, subject, syllabus['source']['file'])
            output[path] = page(path, version, f'{name}: {GUIDES[kind]}', desc, f'{header}\n{body}')
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify the generated pages without writing files')
    args = parser.parse_args()
    try:
        output = build()
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, f'suggestions: {exc}\n')
    if args.check:
        stale = [str(path) for path, html in output.items()
                 if not (ROOT / path).is_file() or (ROOT / path).read_text(encoding='utf-8') != html]
        unexpected = {p.relative_to(ROOT) for p in (ROOT / 'suggestions').rglob('*.html')} - output.keys()
        if stale or unexpected:
            parser.exit(1, 'suggestions: out-of-date or unexpected pages: '
                        + ', '.join(stale + sorted(map(str, unexpected))) + '\n')
    else:
        for path, html in output.items():
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(html, encoding='utf-8')
    print(f'suggestions: {len(output)} static pages {"verified" if args.check else "generated"}')


