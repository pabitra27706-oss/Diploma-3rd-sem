#!/usr/bin/env python3
"""Render static Suggestions pages from curated picks, the syllabus and the PYQ archive."""
from __future__ import annotations

import argparse
from html import escape as e
from pathlib import Path
from urllib.parse import urlencode

from data_pipeline import ROOT, load
from generate_presence import render_presence, shell_version

HUB = 'suggestions/index.html'
GUIDES = {'important-questions': 'Important Questions', 'easy-read': 'Easy Read'}
SUBJECTS = {
    'CST201': ('c', 'C', 'edit'),
    'CST203': ('python', 'Python', 'zap'),
    'CST205': ('data-structures', 'Data Structures', 'layers'),
    'CST207': ('cso', 'Computer System Organization', 'target'),
    'CST209': ('algorithms', 'Algorithms', 'trending-up'),
}
CURATION = 'docs/suggestions/guides.json'
SYLLABUS = 'docs/syllabus/syllabus.json'


def guide_paths():
    return {f'suggestions/{slug}/{kind}.html': code
            for code, (slug, _, _) in SUBJECTS.items() for kind in GUIDES}


def text(value, context):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{context}: expected non-empty text')
    return value.strip()


def archived_questions(root, code):
    directory = root / '_data' / code
    registry = load(directory / 'registry.json')
    items = {}
    for entry in registry['papers']:
        path = directory / entry['fileName']
        paper = load(path)
        if (paper['subject'], paper['fileName'], paper['examSession']) != (code, path.name, entry['examSession']):
            raise ValueError(f'{path.name}: archive and registry do not agree on the subject, filename or session')
        for question in paper['questions']:
            ident = question['id']
            if ident in items or not ident.startswith(f"{code}-{entry['paperCode']}-"):
                raise ValueError(f'{path.name}: unexpected or duplicate question ID {ident}')
            items[ident] = (path.stem, entry, question)
    return items


def icon(name, prefix='../../'):
    return f'<svg class="icon" aria-hidden="true"><use href="{prefix}assets/icons/sprite.svg#{name}"></use></svg>'


