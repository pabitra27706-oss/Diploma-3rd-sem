#!/usr/bin/env python3
"""Mechanical metadata only: counts, key status, candidate/alias reports.
No source-text edits, semantic retags, key imports, or new bank questions.
"""
from collections import defaultdict
from data_pipeline import ROOT, stores, dump, normal, generic_topic, inventory, load


def main():
    papers,banks=stores()
    # PYQ papers and registries are immutable. Only derived quiz/catalog metadata may change.
    for path, bank in banks:
        bank['totalQuestions']=len(bank['questions'])
        for q in bank['questions']:
            q['topicQuality']='generic' if generic_topic(q) else 'specific'
            if q['type']!='mcq' and not any(q.get(k) for k in ('answer','modelAnswer','explanation')):
                q['answerStatus']='missing'
                q['gradable']=False
        path.write_text(dump(bank))
    catalog=inventory(papers,banks)
    (ROOT/'_data/catalog.json').write_text(dump(catalog))
    out=ROOT/'docs/data';out.mkdir(exist_ok=True)
    clusters=catalog['normalizedCandidateClusters']
    lines=['# Duplicate candidates and safe aliases', '', 'Generated by `scripts/build_data_catalog.py`; do not hand-edit.', '', f"Normalized text: {len(clusters)} candidate clusters / {sum(map(len,clusters))} records. These are NOT automatically approved semantic duplicates.", f"Exact content: {len(catalog['canonical'])} groups / {len(catalog['aliases'])} aliases. Canonical selection is earliest year/month, then stable ID; no key is certified by this choice.", '', '## Safe aliases', '', 'Exact equality required for question, options, correct, answer, explanation, type, marks and stored unit, within subject. Raw IDs/files remain intact. Practice omits only aliases; paper browsing still retains all appearances.', '']
    lines += [f"- `{row['id']}` — alsoAppearedIn: "+', '.join(f'`{qid}`' for qid in row['alsoAppearedIn']) for row in catalog['canonical']]
    lines += ['', '## Normalized-text candidates (manual review)', '']
    lines += ['- '+', '.join(f'`{qid}`' for qid in ids) for ids in clusters]
    lines += ['', '## Reprint candidates — not relabelled without source approval', '', 'CST203 P002/P003 and CST209 P002/P003 contain identical question/answer sequences. Their source metadata differs. Files, paper statuses and source labels remain unchanged pending owner confirmation; exact-content aliases already prevent double-counting in Practice.', '']
    (out/'duplicates.md').write_text('\n'.join(lines))
    # Candidate key joins: source identity first, exact normalized text otherwise. Never copy keys.
    text=defaultdict(list);byid={}
    for path,paper in papers:
        for q in paper['questions']:
            byid[q['id']]=(path,paper,q)
            text[(paper['subject'], normal(q['question']))].append(q['id'])
    matches=[];missing=0
    for path,bank in banks:
        for q in bank['questions']:
            if q['type']=='mcq':continue
            candidate=[];method='none'
            sid=q.get('sourceId')
            if sid in byid and byid[sid][1]['subject']==bank['subject']:
                candidate=[sid];method='source-id'
            elif q.get('paperCode') and q.get('sourceNumber'):
                candidate=[qid for qid,(_,p,item) in byid.items() if p['subject']==bank['subject'] and p['paperCode']==q['paperCode'] and item.get('sourceNumber')==q['sourceNumber']]
                if candidate:method='paper-and-source-number'
            if not candidate:
                candidate=text.get((bank['subject'],normal(q['question'])),[])
                if candidate:method='normalized-text-only'
            matches.append({'quizId':q['id'],'bank':path.relative_to(ROOT).as_posix(),'method':method,'candidateIds':candidate,'answerStatus':q.get('answerStatus','missing'),'approved':False})
            missing+=q.get('answerStatus')=='missing'
    (out/'answer-key-candidates.json').write_text(dump({'schemaVersion':1,'notice':'Candidates only; no answer copied or owner verification inferred.','items':matches}))
    review=['# Phase 2 source-verification batch 1', '', 'Generated by `scripts/build_data_catalog.py`. No proposed change below has been applied.', '', '## Seven invalid stored units', '', 'Please verify each against the cited paper and the syllabus PDF. A question may be outside the current syllabus or even misfiled; approval is not implied by a plausible topic match.', '']
    subjects={s['code']:s for s in load(ROOT/'docs/syllabus/syllabus.json')['subjects']}
    for path,paper in papers:
        for q in paper['questions']:
            if q.get('unit',0)>len(subjects[paper['subject']]['units']):
                s=subjects[paper['subject']]
                review += [f"### {q['id']}", f"- Record: `{path.relative_to(ROOT)}`; stored unit: {q['unit']}",f"- Source: {q.get('sourcePage',paper.get('sourceFile'))}",f"- Authority: syllabus PDF p.{s['page']} onwards; {s['title']} has {len(s['units'])} units.",'',q['question'],'', 'Owner action needed: supply confirmed unit, or confirm out-of-syllabus/misfiled disposition. Do not guess.', '']
    review += ['## Other mapping/reprint gates', '', '- CST201 quiz banks U3 (functions) and U4 (arrays) reverse the syllabus ordering. Simply renaming the headers would mislabel questions; confirm a question-level move with old-ID aliases. No move applied.', '- CST209 has a Unit-5 quiz bank, while current syllabus declares four units. Needs source-based disposition, not a silent file rename.', '- Confirm CST203 P002/P003 and CST209 P002/P003 reprint relationships; source metadata is retained.', '', '## Answer-key review: first batch (maximum 40 items)', '', f'{len(matches)} non-MCQ quiz items; {sum(bool(m["candidateIds"]) for m in matches)} have candidate joins, {missing} remain explicitly missing/ungraded. No candidate is owner-verified.', '']
    batch=[m for m in matches if m['candidateIds']][:40]
    for m in batch:
        review += [f"- `{m['quizId']}` ({m['bank']}): {m['method']}; candidates "+', '.join(f'`{qid}` — {byid[qid][2].get("sourcePage",byid[qid][1].get("sourceFile"))}' for qid in m['candidateIds'])]
    review += ['', 'Verify against the cited source before authorizing any answer import; missing states are safe to retain. January 2026 (120 PYQs) remains in the paper browser, not copied into quiz banks pending unit/key review. CST207 is not selectable for quizzes until a source-verified bank exists.', '']
    (out/'source-review-batch-01.md').write_text('\n'.join(review))
    print(f"catalog: {catalog['rawPyqCount']} raw / {catalog['uniquePyqCount']} exact-unique PYQs; {catalog['quizCount']} quiz items; {missing} missing keys")

if __name__=='__main__':main()
