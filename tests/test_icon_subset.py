"""Phase 9.2 — the shipped Font Awesome CSS is a generated subset of the vendor file.

The site loads `assets/vendor/fontawesome/css/used.min.css`, generated by
`scripts/build_icon_subset.py` from the unmodified vendored `all.min.css` and the
icon class names the tree actually uses. That keeps 77 KB of unused icon rules
out of 38 pages' critical path. These tests make the generated file safe:

* it is current (regenerating produces identical bytes);
* every icon class named anywhere in shipped HTML/JS has a rule;
* classes that look like icons but have no rule in the vendor CSS stay listed in
  the manifest as an open finding instead of disappearing silently;
* pages load the subset and not the full vendor stylesheet.
"""

from __future__ import annotations

import importlib.util
import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "assets/vendor/fontawesome"
MANIFEST = VENDOR / "used-icons.json"
SUBSET = VENDOR / "css/used.min.css"


def load_builder():
    spec = importlib.util.spec_from_file_location("build_icon_subset",
                                                 ROOT / "scripts/build_icon_subset.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class IconSubsetTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.builder = load_builder()
        cls.css, cls.manifest = cls.builder.build()
        cls.manifest_file = json.loads(MANIFEST.read_text(encoding="utf-8"))

    def test_generated_files_are_current(self) -> None:
        self.assertEqual(SUBSET.read_text(encoding="utf-8"), self.css,
                         "assets/vendor/fontawesome/css/used.min.css is stale — "
                         "run python3 scripts/build_icon_subset.py")
        self.assertEqual(self.manifest_file, self.manifest,
                         "assets/vendor/fontawesome/used-icons.json is stale")

    def test_subset_is_much_smaller_than_the_vendor_file(self) -> None:
        source = (VENDOR / "css/all.min.css").stat().st_size
        self.assertLess(SUBSET.stat().st_size, source / 3,
                        "the icon subset no longer saves meaningful bytes")
        self.assertGreater(self.manifest["ruleCount"], 0)

    def test_every_used_icon_class_has_a_rule(self) -> None:
        used = self.builder.used_classes()
        source_css = (VENDOR / "css/all.min.css").read_text(encoding="utf-8")
        icon_classes = set(re.findall(r"\.(fa-[a-z0-9-]+):before", source_css))
        missing = sorted(name for name in used if name in icon_classes
                         and f".{name}:before" not in self.css)
        self.assertEqual(missing, [], f"icon classes without a shipped rule: {missing}")

    def test_utility_rules_are_kept(self) -> None:
        for selector in (".fa{", ".fa-spin", ".fa-fw", ".sr-only"):
            self.assertIn(selector, self.css, f"utility rule {selector} was dropped")

    def test_license_banner_is_preserved(self) -> None:
        self.assertTrue(self.css.startswith("/*!\n * Font Awesome Free"),
                        "the MIT/CC-BY/OFL banner must stay at the top of the subset")

    def test_unknown_icon_names_stay_visible(self) -> None:
        # Seven class names look like icons but do not exist in FA 6.5.1 Free.
        # They must be reported, never silently invented or dropped.
        for name in ("fa-cpu", "fa-flow-chart", "fa-formula", "fa-function",
                     "fa-intersection", "fa-split", "fa-wifi-slash"):
            self.assertIn(name, self.manifest["unmatchedClasses"])

    def test_pages_load_the_subset(self) -> None:
        offenders = []
        for page in sorted(ROOT.rglob("*.html")):
            rel = page.relative_to(ROOT)
            if set(rel.parts) & {".git", "webflow", "node_modules", "tests"}:
                continue
            text = page.read_text(encoding="utf-8", errors="replace")
            if "fontawesome/css/all.min.css" in text:
                offenders.append(rel.as_posix())
        self.assertEqual(offenders, [], f"pages still load the full vendor CSS: {offenders}")

    def test_fonts_are_not_rewritten(self) -> None:
        # SIL OFL reserved-name rules mean a font subset would have to be renamed;
        # the subset therefore only touches CSS. Guard the unmodified binaries.
        self.assertEqual(self.manifest["fontsKept"], ["Font Awesome 6 Brands", "Font Awesome 6 Free"])
        for name in ("fa-solid-900.woff2", "fa-brands-400.woff2"):
            self.assertTrue((VENDOR / "webfonts" / name).exists(), name)


if __name__ == "__main__":
    unittest.main()
