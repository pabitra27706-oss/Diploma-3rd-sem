import json
from pathlib import Path
import sys
import unittest
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
from data_pipeline import stores,duplicates,schedule
from build_runtime_bundles import BUNDLES
class RuntimeDerivedTests(unittest.TestCase):
    def test_pools_keep_original_questions(self):
        papers,banks=stores();aliases,_,_=duplicates(papers);assignment,_=schedule(papers)
        expected={q['id']:dict(q,subjectCode=p['subject'],practiceDay=assignment[q['id']]) for _,p in papers for q in p['questions'] if q['id'] not in aliases}
        actual=json.loads((ROOT/'assets/data/practice-pool.json').read_text())['questions']
        self.assertEqual({q['id']:q for q in actual},expected)
        expected={q['id']:dict(q,subject=p['subject'],unit=p['unit']) for _,p in banks for q in p['questions']}
        actual=json.loads((ROOT/'assets/data/quiz-pool.json').read_text())['questions']
        self.assertEqual({q['id']:q for q in actual},expected)
    def test_bundles_match_source_files(self):
        for output,inputs in BUNDLES.items():
            text='/* Generated by scripts/build_runtime_bundles.py; edit source files, then regenerate. */\n'
            for file in inputs:text+='\n;/* Source: '+file+' */\n'+(ROOT/file).read_text()+'\n;\n'
            self.assertEqual((ROOT/output).read_text(),text,output)
    def test_coverage_counts_equal_raw_inventory(self):
        papers,banks=stores();data=json.loads((ROOT/'assets/data/coverage.json').read_text())
        for row in data['units']:
            self.assertEqual(row['pyqCount'],sum(p['subject']==row['subject'] and q.get('unit')==row['unit'] for _,p in papers for q in p['questions']))
            self.assertEqual(row['quizCount'],sum(p['subject']==row['subject'] and q.get('unit')==row['unit'] for _,p in banks for q in p['questions']))
if __name__=='__main__':unittest.main()
