import json
from pathlib import Path
import sys
import unittest
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
from data_pipeline import stores,duplicates,schedule,generic_topic
from build_runtime_data import derived_practice_question
from build_runtime_bundles import BUNDLES
class RuntimeDerivedTests(unittest.TestCase):
    def test_pools_keep_original_questions(self):
        papers,banks=stores();aliases,canonical,_=duplicates(papers);assignment,_=schedule(papers)
        expected={
            q['id']:derived_practice_question(p['subject'],q,assignment,canonical)
            for _,p in papers for q in p['questions'] if q['id'] not in aliases
        }
        pool=json.loads((ROOT/'assets/data/practice-pool.json').read_text())
        self.assertEqual(pool['aliases'],aliases)
        actual=pool['questions']
        self.assertEqual({q['id']:q for q in actual},expected)
        self.assertTrue(any(q.get('alsoAppearedIn') for q in actual))
        for q in actual:
            self.assertEqual(q['topicQuality'],'generic' if generic_topic(q) else 'specific')
        expected={q['id']:dict(q,subject=p['subject'],unit=p['unit']) for _,p in banks for q in p['questions']}
        actual=json.loads((ROOT/'assets/data/quiz-pool.json').read_text())['questions']
        self.assertEqual({q['id']:q for q in actual},expected)
    def test_bundles_match_source_files(self):
        for output,inputs in BUNDLES.items():
            text='/* Generated by scripts/build_runtime_bundles.py; edit source files, then regenerate. */\n'
            for file in inputs:text+='\n;/* Source: '+file+' */\n'+(ROOT/file).read_text()+'\n;\n'
            self.assertEqual((ROOT/output).read_text(),text,output)
    def test_coverage_counts_equal_raw_inventory(self):
        papers,banks=stores();data=json.loads((ROOT/'assets/data/coverage.json').read_text())
        # Quiz items carry no unit of their own: the unit lives on the bank file.
        # Recounting per question object would compare against zero, which is what
        # this assertion silently did before Phase 8 corrected the generator.
        for row in data['units']:
            self.assertEqual(row['pyqCount'],sum(p['subject']==row['subject'] and q.get('unit')==row['unit'] for _,p in papers for q in p['questions']))
            self.assertEqual(row['quizCount'],sum(len(p['questions']) for _,p in banks if p['subject']==row['subject'] and p.get('unit')==row['unit']))
            cards=json.loads((ROOT/f"assets/cards/{row['subject']}.json").read_text())
            self.assertEqual(row['cardCount'],sum(c.get('unit')==row['unit'] for c in cards))
if __name__=='__main__':unittest.main()
