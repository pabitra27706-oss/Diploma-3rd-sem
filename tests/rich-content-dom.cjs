/* Deterministic zero-dependency Node DOM & HTML suite for StudyRichContent (Phase 18.1). */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { ROOT, assert, createMiniDom } = require('./lib/minidom.cjs');
const Rich = require('../assets/js/rich-content.js');

/* 1. Static safety checks on assets/js/rich-content.js */
{
  const src = fs.readFileSync(path.join(ROOT, 'assets/js/rich-content.js'), 'utf8');
  assert(!/\.(?:innerHTML|outerHTML)\s*=/.test(src), 'rich-content.js must never assign innerHTML/outerHTML');
  assert(!/insertAdjacentHTML|document\.write/.test(src), 'rich-content.js must never use raw HTML sinks');
  assert(!/\brgba?\s*\(/.test(src) && !/(?<!&)#[0-9a-fA-F]{3,8}\b/.test(src), 'rich-content.js must contain zero raw colours');
}

/* 2. Pipe-safe table splitting with backticked | and || operators */
{
  const cells = Rich.splitTableRow('| **Operator** | `a | b` (Bitwise OR) | `a || b` (Logical OR) |');
  assert.deepEqual(cells, ['**Operator**', '`a | b` (Bitwise OR)', '`a || b` (Logical OR)']);
}

/* 3. [!COMPARE], [!MARKS], [!FORMULA], [!TRAP], bullets, and ASCII diagram rendering in HTML & MiniDom */
{
  const sample = [
    '> [!MARKS] Total 8 marks: a) 4 marks + b) 4 marks',
    '',
    '### a) Hardwired vs Microprogrammed Control [4 Marks]',
    '',
    '- **Control Signals:** Generated by combinational logic gates vs control memory microinstructions.',
    '- **Flexibility:** Hardwired control is rigid; microprogrammed control updates via control ROM.',
    '',
    '> [!COMPARE] Hardwired vs Microprogrammed Control Unit',
    '> | Parameter | Hardwired Control | Microprogrammed Control |',
    '> | :--- | :---: | ---: |',
    '> | **Speed** | Very fast (`1` clock decode) | Slower (control ROM fetch) |',
    '> | **Bitwise Mask** | Uses `IR | MASK` directly | Uses micro-branch `CAR <- CAR + 1` |',
    '',
    '> [!FORMULA] Effective Memory Access Time',
    '> `EMAT = h * Tc + (1 - h) * (Tc + Tm)`',
    '',
    '```ascii',
    '+--------+     +--------+',
    '|  CPU   | --> | Cache  |',
    '+--------+     +--------+',
    '```'
  ].join('\n');

  const html = Rich.renderHtml(sample);
  assert(html.includes('class="rich-callout rich-callout--marks"'), 'must render [!MARKS] callout');
  assert(html.includes('class="compare-box"'), 'must render [!COMPARE] figure');
  assert(html.includes('class="compare-param"'), 'first column of [!COMPARE] rows must be th.compare-param');
  assert(html.includes('<code>IR | MASK</code>'), 'pipe inside inline code in table cell must stay intact');
  assert(html.includes('class="rich-callout rich-callout--formula"'), 'must render [!FORMULA] callout');
  assert(html.includes('Diagram · 3 lines'), 'ascii fence must render with Diagram label');

  const printHtml = Rich.renderPrintHtml(sample);
  assert(printHtml.includes('class="print-rich-content rich-content"'), 'print renderer must wrap rich content');
  assert(printHtml.includes('class="print-code-block"'), 'print renderer must emit print-code-block');

  const { doc } = createMiniDom('https://example.test/Diploma-3rd-sem/cards.html');
  const host = doc.createElement('div');
  doc.body.appendChild(host);
  Rich.renderDom(doc, host, sample, { compactCard: true });
  assert(host.textContent.includes('Hardwired Control'), 'DOM backend must populate textContent without innerHTML');
  assert.equal(host.querySelectorAll('details').length, 1, 'compactCard mode must fold 6+ blocks into <details>');
}

/* 4. XSS neutrality in both backends */
{
  const payload = 'Attack <img src=x onerror=alert(1)> and `<script>alert(1)</script>`';
  const html = Rich.renderHtml(payload);
  assert(!html.includes('<img') && !html.includes('<script>'), 'HTML backend must escape raw tags');
  const { doc } = createMiniDom('https://example.test/Diploma-3rd-sem/quiz/review.html');
  const host = doc.createElement('div');
  Rich.renderDom(doc, host, payload);
  assert.equal(host.querySelectorAll('img').length, 0);
  assert.equal(host.querySelectorAll('script').length, 0);
}

console.log('PASS StudyRichContent HTML, Print, and pure-DOM suites');
